func TestServerDNSStatic(t *testing.T) {
	a, _ := testApp(t)
	a.serverDNSHostRoot = t.TempDir()
	path := filepath.Join(a.serverDNSHostRoot, "etc", "resolv.conf")
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	nss := filepath.Join(filepath.Dir(path), "nsswitch.conf")
	if err := os.WriteFile(nss, []byte("hosts: files mdns4_minimal [NOTFOUND=return] dns\n"), 0644); err != nil {
		t.Fatal(err)
	}
	original := "# 手动配置\n  nameserver 127.0.0.1 # 本地\nsearch corp.example\nnameserver 192.0.2.1\noptions ndots:2"
	if err := os.WriteFile(path, []byte(original), 0640); err != nil {
		t.Fatal(err)
	}
	const route = "/api/v1/server/dns"
	for _, method := range []string{"GET", "PUT", "POST"} {
		url := route
		if method == "POST" {
			url += "/restore"
		}
		if w := call(a, method, url, "", nil); w.Code != http.StatusUnauthorized {
			t.Fatalf("未登录的 %s 返回 %d", method, w.Code)
		}
	}
	login := call(a, "POST", "/api/v1/auth/login", `{"username":"管理员","password":"test-password"}`, nil)
	cookie := login.Result().Cookies()[0]
	assertStatus := func(w *httptest.ResponseRecorder, edit, restore bool, servers ...string) {
		t.Helper()
		var status serverDNSStatus
		if err := json.Unmarshal(w.Body.Bytes(), &status); w.Code != 200 || err != nil ||
			status.CanEdit != edit || status.CanRestore != restore || !slices.Equal(status.Servers, servers) {
			t.Fatalf("返回 %d：%s，期望地址 %v", w.Code, w.Body.String(), servers)
		}
	}
	initial := call(a, "GET", route, "", cookie)
	assertStatus(initial, true, false, "127.0.0.1", "192.0.2.1")
	if !strings.Contains(initial.Body.String(), `"max_servers":3`) {
		t.Fatalf("静态设置缺少地址数量上限：%s", initial.Body.String())
	}
	if w := call(a, "PUT", route, `{"servers":["192.0.2.10","192.0.2.11","192.0.2.12","192.0.2.13"]}`, cookie); w.Code != 400 {
		t.Fatalf("静态设置应拒绝超过三个地址：%s", w.Body.String())
	}
	for _, bad := range []string{"not-an-ip", "127.0.0.53", "127.0.0.54", "fe80::1", "fe80::1%eth0", "0.0.0.0", "224.0.0.1"} {
		w := call(a, "PUT", route, `{"servers":["`+bad+`"]}`, cookie)
		if w.Code != http.StatusBadRequest {
			t.Fatalf("无效地址 %s 返回 %d：%s", bad, w.Code, w.Body.String())
		}
	}
	if got, err := os.ReadFile(path); err != nil || string(got) != original {
		t.Fatalf("非法地址改变了原文件：%q，%v", got, err)
	}
	assertStatus(call(a, "PUT", route, `{"servers":["2001:0db8::1","::1","192.0.2.10"]}`, cookie), true, true, "2001:db8::1", "::1", "192.0.2.10")
	assertStatus(call(a, "PUT", route, `{"servers":["192.0.2.20"]}`, cookie), true, true, "192.0.2.20")
	updated, err := os.ReadFile(path)
	want := "# 手动配置\n  nameserver 192.0.2.20 # 本地\nsearch corp.example\noptions ndots:2"
	if err != nil || string(updated) != want {
		t.Fatalf("保存后的文件为 %q，%v", updated, err)
	}

	assertStatus(call(a, "POST", route+"/restore", "", cookie), true, false, "127.0.0.1", "192.0.2.1")
	if got, err := os.ReadFile(path); err != nil || string(got) != original {
		t.Fatalf("恢复后原文件字节变化：%q，%v", got, err)
	}

	assertStatus(call(a, "PUT", route, `{"servers":["192.0.2.20","192.0.2.21"]}`, cookie), true, true, "192.0.2.20", "192.0.2.21")
	edited := "# 管理员说明\n  nameserver 192.0.2.20 # 新说明\nsearch new.example\nnameserver 192.0.2.21\noptions ndots:3"
	if err := os.WriteFile(path, []byte(edited), 0640); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(path, 0600); err != nil {
		t.Fatal(err)
	}
	assertStatus(call(a, "POST", route+"/restore", "", cookie), true, false, "127.0.0.1", "192.0.2.1")
	merged := strings.NewReplacer("192.0.2.20", "127.0.0.1", "192.0.2.21", "192.0.2.1").Replace(edited)
	if got, err := os.ReadFile(path); err != nil || string(got) != merged {
		t.Fatalf("恢复未保留管理员更新：%q，%v", got, err)
	}
	if info, err := os.Stat(path); err != nil || info.Mode().Perm() != 0600 {
		t.Fatalf("文件权限未保留：%v，%v", info, err)
	}

	for _, hosts := range []string{"files", "files resolve [!UNAVAIL=return] dns"} {
		if err := os.WriteFile(nss, []byte("hosts: "+hosts+"\n"), 0644); err != nil {
			t.Fatal(err)
		}
		assertStatus(call(a, "GET", route, "", cookie), false, false)
	}
	if err := os.WriteFile(nss, []byte("hosts: files dns\n"), 0644); err != nil {
		t.Fatal(err)
	}
	empty := []byte("options ndots:2")
	if err := os.WriteFile(path, empty, 0640); err != nil {
		t.Fatal(err)
	}
	assertStatus(call(a, "GET", route, "", cookie), true, false, "127.0.0.1")
	assertStatus(call(a, "PUT", route, `{"servers":["::1"]}`, cookie), true, true, "::1")
	assertStatus(call(a, "POST", route+"/restore", "", cookie), true, false, "127.0.0.1")
	if got, err := os.ReadFile(path); err != nil || string(got) != string(empty) {
		t.Fatalf("空地址恢复改变了无尾换行的原文件：%q，%v", got, err)
	}
	if err := os.WriteFile(path, []byte("# Generated by NetworkManager\nnameserver 192.0.2.9\n"), 0640); err != nil {
		t.Fatal(err)
	}
	assertStatus(call(a, "GET", route, "", cookie), false, false, "192.0.2.9")
}

func TestServerDNSResolved(t *testing.T) {
	a, _ := testApp(t)
	a.serverDNSHostRoot = t.TempDir()
	path := filepath.Join(a.serverDNSHostRoot, "etc", "resolv.conf")
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	nss := filepath.Join(filepath.Dir(path), "nsswitch.conf")
	if err := os.WriteFile(nss, []byte("hosts: files\n"), 0644); err != nil {
		t.Fatal(err)
	}
	const stub = "../run/systemd/resolve/stub-resolv.conf"
	if err := os.Symlink(stub, path); err != nil {
		t.Fatal(err)
	}
	dropIn := filepath.Join(a.serverDNSHostRoot, serverDNSDropIn)
	var globalDNS, globalRoute string
	linkRoute := "~corp.example"
	applyFailed, routeUnavailable, routeIncomplete := false, false, false
	a.Command = func(_ context.Context, name string, args ...string) ([]byte, error) {
		switch name + " " + strings.Join(args, " ") {
		case "resolvectl dns":
			return []byte("Global: " + globalDNS + "\nLink 2 (wanqa): 192.0.2.1\nLink 3 (corpqa): 192.0.2.2\n"), nil
		case "resolvectl domain":
			return []byte("Global: example.org " + globalRoute + "\nLink 2 (wanqa):\nLink 3 (corpqa): " + linkRoute + "\n"), nil
		case "resolvectl default-route":
			if routeUnavailable {
				return nil, errors.New("读取链路失败")
			}
			if routeIncomplete {
				return []byte("Global\nLink 3 (corpqa): no\n"), nil
			}
			return []byte("Global\n       Protocols: -LLMNR\nresolv.conf mode: stub\nLink 2 (wanqa): yes\nLink 3 (corpqa): no\n"), nil
		case "systemctl reload-or-restart systemd-resolved.service":
			if applyFailed {
				return nil, nil
			}
			data, err := os.ReadFile(dropIn)
			if errors.Is(err, os.ErrNotExist) {
				globalDNS, globalRoute = "", ""
				return nil, nil
			}
			if err != nil || !strings.HasPrefix(string(data), "[Resolve]\nDNS=\nDNS=") || !strings.HasSuffix(string(data), "\nDomains=~.\n") {
				t.Fatalf("配置片段错误：%q，%v", data, err)
			}
			globalDNS = strings.Split(string(data), "\n")[2][len("DNS="):]
			globalRoute = "~."
			return nil, nil
		default:
			t.Fatalf("意外命令：%s %v", name, args)
			return nil, nil
		}
	}
	login := call(a, "POST", "/api/v1/auth/login", `{"username":"管理员","password":"test-password"}`, nil)
	cookie := login.Result().Cookies()[0]
	const route = "/api/v1/server/dns"
	assertStatus := func(method, path, body string, edit, restore bool, servers ...string) {
		t.Helper()
		w := call(a, method, path, body, cookie)
		var status serverDNSStatus
		if err := json.Unmarshal(w.Body.Bytes(), &status); w.Code != 200 || err != nil || status.CanEdit != edit ||
			status.CanRestore != restore || status.MaxServers != 0 || !slices.Equal(status.Servers, servers) {
			t.Fatalf("返回 %d：%s，期望地址 %v", w.Code, w.Body.String(), servers)
		}
	}
	assertStatus("GET", route, "", false, false)
	if err := os.WriteFile(nss, []byte("hosts: files resolve [!UNAVAIL=return] dns\n"), 0644); err != nil {
		t.Fatal(err)
	}
	assertStatus("GET", route, "", true, false, "192.0.2.1")
	linkRoute = "~corp.example ~."
	assertStatus("GET", route, "", false, false, "192.0.2.2")
	if w := call(a, "PUT", route, `{"servers":["192.0.2.20"]}`, cookie); w.Code != 409 {
		t.Fatalf("默认链路冲突没有阻止修改：%s", w.Body.String())
	}
	linkRoute = "~corp.example"

	applyFailed = true
	if w := call(a, "PUT", route, `{"servers":["192.0.2.30"]}`, cookie); w.Code != 500 || !strings.Contains(w.Body.String(), "dns_readback_error") {
		t.Fatalf("回读不一致应报告失败：%s", w.Body.String())
	}
	assertStatus("GET", route, "", true, true, "192.0.2.1")
	routeUnavailable = true
	assertStatus("GET", route, "", false, true)
	routeUnavailable, routeIncomplete = false, true
	assertStatus("GET", route, "", false, true)
	routeIncomplete, applyFailed = false, false
	assertStatus("PUT", route, `{"servers":["127.0.0.1","2001:db8::11","2001:db8::12","2001:db8::13"]}`,
		true, true, "127.0.0.1", "2001:db8::11", "2001:db8::12", "2001:db8::13")
	assertStatus("POST", route+"/restore", "", true, false, "192.0.2.1")
	if target, err := os.Readlink(path); err != nil || target != stub {
		t.Fatalf("符号链接被修改：%q，%v", target, err)
	}
	if _, err := os.Stat(dropIn); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("恢复后配置片段仍存在：%v", err)
	}
}
